"""Build content/routes.geojson from content/routes.yaml + OpenStreetMap ways (data/raw/osm.json).

Each route segment lists OSM way ids in walking order. Ways are oriented and joined into one
line per segment; gaps between consecutive ways or segments are reported so the spec can be
fixed. The output is committed to the repo (it is content), so the viewer build does not need
OSM at hand.
"""
from __future__ import annotations

import json
import math
import sys

import yaml

from common import RAW_DIR, REPO_DIR

GAP_WARN_M = 60


def dist_m(a, b) -> float:
    k = math.cos(math.radians((a[1] + b[1]) / 2))
    return math.hypot((b[0] - a[0]) * 111_320 * k, (b[1] - a[1]) * 110_540)


def main() -> int:
    spec = yaml.safe_load((REPO_DIR / "content" / "routes.yaml").read_text())
    osm = json.loads((RAW_DIR / "osm.json").read_text())
    ways = {e["id"]: [(p["lon"], p["lat"]) for p in e["geometry"]]
            for e in osm["elements"] if e["type"] == "way" and "geometry" in e}

    features, problems = [], 0
    for route in spec["routes"]:
        # Flatten all ways of the route, orient each to continue from the previous one.
        seq = [(si, wid) for si, seg in enumerate(route["segments"]) for wid in seg["osm_ways"]]
        missing = [wid for _, wid in seq if wid not in ways]
        if missing:
            print(f"{route['id']}: OSM ways not found in data/raw/osm.json: {missing}", file=sys.stderr)
            return 1
        lines: list[list[tuple[float, float]]] = [[] for _ in route["segments"]]
        prev_end = None
        for i, (si, wid) in enumerate(seq):
            pts = ways[wid]
            if prev_end is None:
                # Orient the first way so it ends near the next way (if any).
                if i + 1 < len(seq):
                    nxt = ways[seq[i + 1][1]]
                    ends = (nxt[0], nxt[-1])
                    if min(dist_m(pts[0], e) for e in ends) < min(dist_m(pts[-1], e) for e in ends):
                        pts = pts[::-1]
            elif dist_m(prev_end, pts[-1]) < dist_m(prev_end, pts[0]):
                pts = pts[::-1]
            if prev_end is not None:
                gap = dist_m(prev_end, pts[0])
                if gap > GAP_WARN_M:
                    problems += 1
                    print(f"  ! {route['id']}: gap of {gap:.0f} m before way {wid}")
            seg_line = lines[si]
            seg_line.extend(pts if not seg_line or seg_line[-1] != pts[0] else pts[1:])
            prev_end = pts[-1]

        segments = []
        for seg, line in zip(route["segments"], lines):
            length = sum(dist_m(a, b) for a, b in zip(line, line[1:]))
            segments.append({"mode": seg["mode"], "name": seg["name"], "osm_ways": seg["osm_ways"],
                             "length_m": round(length)})
        features.append({
            "type": "Feature",
            "geometry": {"type": "MultiLineString",
                         "coordinates": [[[round(x, 7), round(y, 7)] for x, y in ln] for ln in lines]},
            "properties": {k: route[k] for k in ("id", "name", "summit", "stops", "description") if k in route}
            | {"segments": segments},
        })
        total = sum(s["length_m"] for s in segments)
        print(f"{route['id']}: {len(segments)} segments, {total / 1000:.1f} km (map distance)")

    out = REPO_DIR / "content" / "routes.geojson"
    out.write_text(json.dumps({"type": "FeatureCollection", "name": "elbrus-routes",
                               "_note": "Generated by pipeline/build_routes.py from routes.yaml + OSM. Edit routes.yaml, not this file.",
                               "features": features}, ensure_ascii=False, indent=1))
    print(f"Wrote {out.relative_to(REPO_DIR)}" + (f" with {problems} gap warning(s)" if problems else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
